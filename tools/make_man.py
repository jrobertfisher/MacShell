#!/usr/bin/env python3
"""Turns the manual pages in man/*.txt into Rez 'TEXT' resources for man.

Each page's NAME line ("    ls, dir - list a folder's contents") gives its
names. The page is stored once per name, so aliases work with
GetNamedResource: the first name at IDs from 3000 (man -k lists these),
aliases at IDs from 3500.

Usage: make_man.py <output man.r> <page.txt ...>
"""
import os
import sys

FIRST_ID, ALIAS_ID = 3000, 3500


def names_of(text, path):
    lines = text.split('\n')
    if len(lines) < 2 or lines[0] != 'NAME' or ' - ' not in lines[1]:
        sys.exit(f'{path}: the page must start with NAME and "    name - summary"')
    return [n.strip() for n in lines[1].strip().split(' - ', 1)[0].split(',')]


def rez(rid, name, data):
    hexed = data.hex().upper()
    rows = [hexed[i:i + 64] for i in range(0, len(hexed), 64)]
    body = '\n'.join('\t$"%s"' % ' '.join(r[j:j + 4] for j in range(0, len(r), 4)) for r in rows)
    return 'data \'TEXT\' (%d, "%s", purgeable) {\n%s\n};\n\n' % (rid, name, body)


def main(out_path, pages):
    out = ['/* Manual pages for man, generated by tools/make_man.py from man/*.txt. */\n\n']
    first, alias, seen = FIRST_ID, ALIAS_ID, set()
    for path in sorted(pages):
        text = open(path, encoding='ascii').read()
        data = text.encode('mac_roman')
        for i, name in enumerate(names_of(text, path)):
            if name in seen:
                sys.exit(f'{path}: "{name}" is already used by another page')
            seen.add(name)
            if i == 0:
                out.append(rez(first, name, data))
                first += 1
            else:
                out.append(rez(alias, name, data))
                alias += 1
    if first > ALIAS_ID:
        sys.exit('too many pages for the ID range')
    with open(out_path, 'w') as f:
        f.write(''.join(out))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2:])
